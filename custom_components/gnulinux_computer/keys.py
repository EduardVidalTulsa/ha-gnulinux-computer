"""The SSH key pair of Home Assistant, shared by every computer of the pool."""

from __future__ import annotations

import logging
import os
import shlex
from typing import TYPE_CHECKING

import asyncssh

from homeassistant.const import CONF_HOST, CONF_PASSWORD, CONF_PORT, CONF_USERNAME
from homeassistant.core import HomeAssistant
from homeassistant.exceptions import HomeAssistantError

from .client import CannotConnect, CommandError, LinuxClient, load_private_key
from .const import (
    AUTH_GENERATE,
    AUTH_PASSWORD,
    CONF_AUTH_METHOD,
    CONF_HOST_KEY,
    CONF_KEY_PATH,
    CONF_SUDO_PASSWORD,
    DEFAULT_PORT,
    KEY_DIR,
    SHARED_KEY_COMMENT,
    SHARED_KEY_PATH,
)

if TYPE_CHECKING:
    from homeassistant.config_entries import ConfigEntry

_LOGGER = logging.getLogger(__name__)


def generate_key(path: str = SHARED_KEY_PATH, comment: str = SHARED_KEY_COMMENT) -> str:
    """Create the ed25519 key pair if it does not exist (blocking).

    Return the public key in OpenSSH format. The private key is created with
    mode 0600 from the start (never readable by others, not even briefly).
    """
    if not os.path.exists(path):
        os.makedirs(os.path.dirname(path), mode=0o700, exist_ok=True)
        key = asyncssh.generate_private_key("ssh-ed25519", comment=comment)
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(fd, "wb") as handle:
            handle.write(key.export_private_key())
        key.write_public_key(path + ".pub")
    return asyncssh.read_private_key(path).export_public_key().decode().strip()


def _public_blob(path: str) -> str | None:
    """Base64 body of the public key that belongs to a private key file."""
    try:
        parts = asyncssh.read_private_key(path).export_public_key().decode().split()
    except (OSError, ValueError, asyncssh.KeyImportError):
        return None
    return parts[1] if len(parts) > 1 else None


_INSTALL_KEY = r"""
umask 077
mkdir -p "$HOME/.ssh"
f="$HOME/.ssh/authorized_keys"
[ -e "$f" ] || : > "$f"
if ! grep -qF -- "$BLOB" "$f"; then
  [ -n "$(tail -c 1 "$f")" ] && echo >> "$f"
  printf '%s\n' "$KEY" >> "$f"
fi
"""

_REMOVE_KEY = r"""
f="$HOME/.ssh/authorized_keys"
[ -e "$f" ] || exit 0
t=$(mktemp "$f.XXXXXX") || exit 1
grep -vF -- "$OLD" "$f" > "$t"
cat "$t" > "$f"
rm -f "$t"
"""


async def async_use_shared_key(
    hass: HomeAssistant, entry: ConfigEntry, *, remove_old: bool = True
) -> str:
    """Switch a computer to the shared key of the pool.

    Uses the current credentials to authorize the shared public key, checks
    that logging in with it works, and only then changes the entry. The old
    public key is removed from the computer when it was one generated by this
    integration for that computer alone.
    """
    data = dict(entry.data)
    old_path = data.get(CONF_KEY_PATH) if data.get(CONF_AUTH_METHOD) != AUTH_PASSWORD else None
    if old_path == SHARED_KEY_PATH:
        return "already"
    runtime = getattr(entry, "runtime_data", None)
    if runtime is None:
        raise HomeAssistantError(f"{entry.title} no està carregat")

    pubkey = await hass.async_add_executor_job(generate_key)
    blob = pubkey.split()[1]
    try:
        res = await runtime.client.run(
            f"KEY={shlex.quote(pubkey)}; BLOB={shlex.quote(blob)}\n" + _INSTALL_KEY, timeout=30
        )
    except (CannotConnect, CommandError) as err:
        raise HomeAssistantError(f"{entry.title} no respon: {err}") from err
    if not res.ok:
        raise HomeAssistantError(f"{entry.title}: {res.stderr.strip() or res.exit_status}")

    # Prove that the shared key works before touching the entry.
    sudo_password = data.get(CONF_SUDO_PASSWORD) or data.get(CONF_PASSWORD) or None
    test = LinuxClient(
        data[CONF_HOST],
        data.get(CONF_PORT, DEFAULT_PORT),
        data[CONF_USERNAME],
        private_key=await hass.async_add_executor_job(load_private_key, SHARED_KEY_PATH),
        sudo_password=sudo_password,
        host_key=data.get(CONF_HOST_KEY),
    )
    try:
        check = await test.run("true", timeout=30)
    except (CannotConnect, CommandError) as err:
        raise HomeAssistantError(
            f"{entry.title}: la clau compartida s'ha afegit però no permet entrar ({err}); "
            "no s'ha canviat res a Home Assistant"
        ) from err
    else:
        if not check.ok:
            raise HomeAssistantError(f"{entry.title}: prova amb la clau compartida fallida")
        removed = False
        old_blob = None
        if (
            remove_old
            and old_path
            and os.path.basename(old_path).startswith("gnulinux_")
            and os.path.dirname(old_path) == KEY_DIR
        ):
            old_blob = await hass.async_add_executor_job(_public_blob, old_path)
        if old_blob and old_blob != blob:
            res = await test.run(f"OLD={shlex.quote(old_blob)}\n" + _REMOVE_KEY, timeout=30)
            removed = res.ok
    finally:
        await test.close()

    data[CONF_AUTH_METHOD] = AUTH_GENERATE
    data[CONF_KEY_PATH] = SHARED_KEY_PATH
    if sudo_password:
        data[CONF_SUDO_PASSWORD] = sudo_password
    data.pop(CONF_PASSWORD, None)
    _LOGGER.info("%s now uses the shared key %s", entry.title, SHARED_KEY_PATH)
    hass.config_entries.async_update_entry(entry, data=data)  # reloads the entry
    return "switched_old_removed" if removed else "switched"
